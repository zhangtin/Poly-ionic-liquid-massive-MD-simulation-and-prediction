#!/usr/bin/env python3
"""Regenerate ``conf.gro`` from the upstream GROMACS ``spc216.gro`` box.

PROJECT-CREATED helper (not part of GROMACS). It replicates the
pre-equilibrated 216-water box shipped with GROMACS (share/top/spc216.gro)
N x N x N times by pure periodic translation, renumbers residues/atoms and
writes the enlarged box. No coordinates are perturbed and no molecules are
removed: spc216.gro is a periodic, equilibrated box, so tiling it is the same
operation ``gmx solvate -cs spc216.gro`` performs for an exactly matching box.

Why: a single 216-water box is 1.862 nm wide, which is smaller than twice the
1.0 nm cut-offs used by the base protocol. A 2x2x2 tiling gives 1728 waters in
a 3.724 nm cubic box.

Usage (from the base project directory):
    python3 tools/make_conf.py upstream/spc216.gro conf.gro --n 2
"""
from __future__ import annotations

import argparse
from pathlib import Path


def read_gro(path: Path):
    lines = path.read_text().splitlines()
    title = lines[0]
    natoms = int(lines[1].strip())
    atoms = []
    for line in lines[2 : 2 + natoms]:
        resnr = int(line[0:5])
        resname = line[5:10].strip()
        atomname = line[10:15].strip()
        x, y, z = float(line[20:28]), float(line[28:36]), float(line[36:44])
        atoms.append((resnr, resname, atomname, x, y, z))
    box = [float(v) for v in lines[2 + natoms].split()]
    if len(box) != 3 or not (box[0] == box[1] == box[2]):
        raise SystemExit("expected a cubic rectangular box in the source file")
    return title, atoms, box


def tile(atoms, box, n: int):
    out = []
    nres_src = max(a[0] for a in atoms)
    block = 0
    for i in range(n):
        for j in range(n):
            for k in range(n):
                shift = (i * box[0], j * box[1], k * box[2])
                for resnr, resname, atomname, x, y, z in atoms:
                    out.append(
                        (
                            resnr + block * nres_src,
                            resname,
                            atomname,
                            x + shift[0],
                            y + shift[1],
                            z + shift[2],
                        )
                    )
                block += 1
    return out, [b * n for b in box]


def write_gro(path: Path, title: str, atoms, box) -> None:
    lines = [title, f"{len(atoms):5d}"]
    for idx, (resnr, resname, atomname, x, y, z) in enumerate(atoms, start=1):
        lines.append(
            f"{resnr % 100000:5d}{resname:<5s}{atomname:>5s}{idx % 100000:5d}"
            f"{x:8.3f}{y:8.3f}{z:8.3f}"
        )
    lines.append(f"{box[0]:10.5f}{box[1]:10.5f}{box[2]:10.5f}")
    path.write_text("\n".join(lines) + "\n")


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("source", type=Path)
    ap.add_argument("dest", type=Path)
    ap.add_argument("--n", type=int, default=2, help="replication factor per axis")
    args = ap.parse_args()
    _, atoms, box = read_gro(args.source)
    tiled, newbox = tile(atoms, box, args.n)
    nmol = len(tiled) // 3
    title = (
        f"SPC/E water, {nmol} molecules: {args.n}x{args.n}x{args.n} tiling of "
        "GROMACS share/top/spc216.gro (generated by tools/make_conf.py)"
    )
    write_gro(args.dest, title, tiled, newbox)
    print(f"wrote {args.dest}: {nmol} molecules, box {newbox[0]:.5f} nm")


if __name__ == "__main__":
    main()
